def _is_missing(value: object) -> bool:
    if value is None:
        return True
    return bool(pd.isna(value))


def _text_or_none(value: object) -> str | None:
    if _is_missing(value):
        return None
    text = unicodedata.normalize("NFKC", str(value))
    cleaned = " ".join(text.split())
    return cleaned or None


def _issue(
    entity: str,
    source_key: object,
    reason: str,
    detail: str,
) -> dict[str, str]:
    return {
        "entity": entity,
        "source_key": str(source_key),
        "reason": reason,
        "detail": detail,
    }


def _records_frame(
    records: list[dict[str, object]],
    columns: tuple[str, ...],
) -> pd.DataFrame:
    if not records:
        return _empty_frame(columns)
    return pd.DataFrame.from_records(records).loc[:, list(columns)]


def _stable_id(prefix: str, *parts: object, maximum: int = 64) -> str:
    payload = "\x1f".join(
        "<NULL>" if _is_missing(part) else str(part) for part in parts
    )
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    return f"{prefix}{digest[: maximum - len(prefix)]}"


def _single_group_value(
    group: pd.DataFrame,
    column: str,
    *,
    required: bool,
) -> tuple[object, str | None]:
    values = group[column]
    missing_mask = values.map(_is_missing)
    non_missing = values.loc[~missing_mask].drop_duplicates()

    if len(non_missing) > 1:
        if not required:
            return pd.NA, None
        return None, f"CONFLICTING_{column.upper()}"
    if bool(missing_mask.any()) and len(non_missing) == 1:
        if not required:
            return pd.NA, None
        return None, f"MIXED_MISSING_{column.upper()}"
    if non_missing.empty:
        if required:
            return None, f"MISSING_{column.upper()}"
        return pd.NA, None
    return non_missing.iloc[0], None


def _url_evidence_by_game(
    core_data: OracleCoreData,
) -> tuple[dict[str, str | None], dict[str, str]]:
    """Keep URL evidence only when every source row agrees.

    URL is optional target metadata.  Mixed missing or conflicting values must
    not reject an otherwise usable game, but neither condition may be resolved
    by selecting one URL for series evidence.
    """

    urls: dict[str, str | None] = {}
    anomalies: dict[str, str] = {}
    source = core_data.dataframe
    valid_gameids = source.loc[~source["gameid"].map(_is_missing)]
    for gameid, group in valid_gameids.groupby(
        "gameid",
        sort=False,
        dropna=False,
    ):
        source_key = str(gameid)
        cleaned = [_text_or_none(value) for value in group["url"].tolist()]
        non_missing = {value for value in cleaned if value is not None}
        has_missing = any(value is None for value in cleaned)
        if len(non_missing) > 1:
            urls[source_key] = None
            anomalies[source_key] = "URL_VALUES_CONFLICT"
        elif len(non_missing) == 1 and has_missing:
            urls[source_key] = None
            anomalies[source_key] = "URL_MIXED_MISSING"
        elif non_missing:
            urls[source_key] = next(iter(non_missing))
        else:
            urls[source_key] = None
    return urls, anomalies


def _collapse_game_metadata(
    core_data: OracleCoreData,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    source = core_data.dataframe
    required_columns = {
        "gameid",
        "url",
        "league",
        "year",
        "split",
        "playoffs",
        "date",
        "game",
        "patch",
    }
    missing_columns = sorted(required_columns - set(source.columns))
    if missing_columns:
        raise ValueError(
            "Oracle core data is missing transform columns: "
            + ", ".join(missing_columns)
        )

    records: list[dict[str, object]] = []
    rejected: list[dict[str, str]] = []
    missing_gameid = source["gameid"].map(_is_missing)
    if bool(missing_gameid.any()):
        sample_indices = source.index[missing_gameid].tolist()[:20]
        raise ValueError(
            "Oracle transform cannot establish game grain because gameid is "
            f"missing for {int(missing_gameid.sum())} source row(s); "
            f"sample_indices={sample_indices}. No source or target ID was "
            "fabricated."
        )

    grouped = source.loc[~missing_gameid].groupby(
        "gameid",
        sort=False,
        dropna=False,
    )
    fields = (
        ("url", False),
        ("league", True),
        ("year", True),
        ("split", True),
        ("playoffs", True),
        ("date", True),
        ("game", True),
        ("patch", True),
    )

    for gameid, group in grouped:
        record: dict[str, object] = {"gameid": str(gameid)}
        reasons: list[str] = []
        for column, required in fields:
            value, reason = _single_group_value(
                group,
                column,
                required=required,
            )
            record[column] = value
            if reason is not None:
                reasons.append(reason)

        if not reasons:
            game_number = int(record["game"])
            season = int(record["year"])
            patch = str(record["patch"])
            if not 1 <= game_number <= 32767:
                reasons.append("INVALID_GAME_NUMBER")
            if not -32768 <= season <= 32767:
                reasons.append("INVALID_SOURCE_YEAR")
            if len(patch) > 20:
                reasons.append("PATCH_TOO_LONG")
            if len(str(gameid)) > 100:
                reasons.append("GAME_ID_TOO_LONG")

        if reasons:
            rejected.append(
                _issue(
                    "game",
                    gameid,
                    "GAME_METADATA_INVALID",
                    ",".join(sorted(reasons)),
                )
            )
            continue
        records.append(record)

    columns = (
        "gameid",
        "url",
        "league",
        "year",
        "split",
        "playoffs",
        "date",
        "game",
        "patch",
    )
    return (
        _records_frame(records, columns),
        _records_frame(rejected, ISSUE_COLUMNS),
    )


def _series_key_from_gameid(
    gameid: str,
    game_number: int,
) -> tuple[str | None, str | None]:
    match = _GAME_SERIES_PATTERN.fullmatch(gameid)
    if match is None:
        return None, None
    encoded_number = int(match.group("number"))
    if encoded_number != game_number:
        return None, "GAMEID_GAME_NUMBER_CONFLICT"
    key = _text_or_none(match.group("series"))
    if key is None:
        return None, "EMPTY_GAMEID_SERIES_KEY"
    return key, None


def _series_key_from_url(url: object) -> tuple[str | None, str | None]:
    text = _text_or_none(url)
    if text is None:
        return None, None
    try:
        parsed = urlsplit(text)
    except ValueError:
        return None, "INVALID_URL_EVIDENCE"
    parameters = parse_qs(parsed.query, keep_blank_values=False)
    candidates: list[str] = []
    for name in _URL_SERIES_PARAMETERS:
        values = sorted(set(parameters.get(name, ())))
        candidates.extend(
            f"{parsed.netloc.casefold()}?{name}={value}"
            for value in values
            if value
        )
    candidates = sorted(set(candidates))
    if len(candidates) > 1:
        return None, "AMBIGUOUS_URL_SERIES_KEY"
    if not candidates:
        return None, None
    return candidates[0], None


def _explicit_best_of(*values: object) -> tuple[int | None, str | None]:
    candidates: set[int] = set()
    for value in values:
        text = _text_or_none(value)
        if text is None:
            continue
        try:
            parsed = urlsplit(text)
        except ValueError:
            # URL evidence is diagnosed by ``_series_key_from_url``.  It must
            # not crash or contribute a best-of token after parsing failed.
            continue
        candidates.update(
            int(match.group("best_of"))
            for match in _BEST_OF_TOKEN_PATTERN.finditer(text)
        )
        parameters = parse_qs(parsed.query, keep_blank_values=False)
        for name in _URL_BEST_OF_PARAMETERS:
            for parameter_value in parameters.get(name, ()):
                normalized = parameter_value.strip().casefold()
                if normalized.startswith("bo"):
                    normalized = normalized[2:]
                if normalized in {"1", "3", "5"}:
                    candidates.add(int(normalized))

    if len(candidates) > 1:
        return None, "EXPLICIT_BEST_OF_CONFLICT"
    if not candidates:
        return None, "EXPLICIT_BEST_OF_MISSING"
    return next(iter(candidates)), None


def _team_pair_by_game(
    identity_result: OracleIdentityResult,
) -> dict[str, tuple[str, str]]:
    teams = identity_result.team_participations
    required = {"gameid", "resolved_oracle_team_id"}
    if not required <= set(teams.columns):
        raise ValueError("Oracle team resolutions are missing series columns.")

    pairs: dict[str, tuple[str, str]] = {}
    for gameid, group in teams.groupby("gameid", sort=False, dropna=False):
        values = sorted(
            {
                str(value)
                for value in group["resolved_oracle_team_id"].tolist()
                if not _is_missing(value)
            }
        )
        if len(values) == 2:
            pairs[str(gameid)] = (values[0], values[1])
    return pairs


def analyze_series_evidence(
    core_data: OracleCoreData,
    identity_result: OracleIdentityResult,
) -> OracleSeriesAnalysis:
    """Resolve only source-explicit series keys and best-of tokens.

    Team pair, date, and game number validate a source key.  They are never
    used to manufacture a key or infer BO1/BO3/BO5.
    """

    games, metadata_rejected = _collapse_game_metadata(core_data)
    pairs = _team_pair_by_game(identity_result)
    urls_by_game, url_anomalies = _url_evidence_by_game(core_data)
    candidates: list[dict[str, object]] = []
    assignments: list[dict[str, object]] = []
    diagnostics: list[dict[str, str]] = []
    url_gameid_conflicts: set[str] = set()

    valid_gameids = {str(value) for value in games["gameid"].tolist()}
    url_to_gameids: dict[str, set[str]] = {}
    for gameid, source_url in urls_by_game.items():
        if gameid not in valid_gameids or source_url is None:
            continue
        url_to_gameids.setdefault(source_url, set()).add(gameid)
    for related_gameids in url_to_gameids.values():
        if len(related_gameids) > 1:
            url_gameid_conflicts.update(related_gameids)

    for row in games.itertuples(index=False):
        gameid = str(row.gameid)
        game_number = int(row.game)
        source_url = urls_by_game.get(gameid)
        gameid_key, gameid_reason = _series_key_from_gameid(
            gameid,
            game_number,
        )
        url_key, url_reason = _series_key_from_url(source_url)
        reasons = [
            reason
            for reason in (gameid_reason, url_reason)
            if reason is not None
        ]
        url_anomaly = url_anomalies.get(gameid)
        if url_anomaly is not None:
            reasons.append(url_anomaly)
        source_key = gameid_key or url_key
        if gameid_key is not None and url_key is not None:
            source_key = gameid_key

        best_of, best_of_reason = _explicit_best_of(gameid, source_url)
        if best_of_reason is not None:
            reasons.append(best_of_reason)
        if source_key is None:
            reasons.append("SOURCE_SERIES_KEY_MISSING")
        if gameid in url_gameid_conflicts:
            reasons.append("URL_TO_GAMEID_CONFLICT")
        if gameid not in pairs:
            reasons.append("TEAM_PAIR_UNRESOLVED")

        if reasons:
            reason = ",".join(sorted(set(reasons)))
            assignments.append(
                {
                    "gameid": gameid,
                    "series_id": pd.NA,
                    "series_status": SERIES_BLOCKED,
                    "series_reason": reason,
                }
            )
            diagnostics.append(
                {
                    "source_key": gameid,
                    "status": SERIES_BLOCKED,
                    "reason": reason,
                    "detail": "No series record was created for this game.",
                }
            )
            continue

        candidates.append(
            {
                "gameid": gameid,
                "source_series_key": str(source_key),
                "url_series_key": url_key,
                "source_url": source_url,
                "league": row.league,
                "year": row.year,
                "split": row.split,
                "playoffs": row.playoffs,
                "date": row.date,
                "game_number": game_number,
                "team_pair": pairs[gameid],
                "best_of": int(best_of),
            }
        )

    candidate_frame = pd.DataFrame.from_records(candidates)
    series_records: list[dict[str, object]] = []
    conflicting_source_keys: set[str] = set()
    if not candidate_frame.empty:
        # A URL-derived identifier may describe several games in one series;
        # the exact URL -> gameid dependency was validated above.  Neither form
        # may point at several source series.  URL/date/team pair never
        # manufacture a series key.
        for relation_column in ("url_series_key", "source_url"):
            relation_rows = candidate_frame.loc[
                ~candidate_frame[relation_column].map(_is_missing)
            ]
            for _, relation_group in relation_rows.groupby(
                relation_column,
                sort=False,
                dropna=False,
            ):
                related_keys = {
                    str(value)
                    for value in relation_group["source_series_key"].tolist()
                }
                if len(related_keys) > 1:
                    conflicting_source_keys.update(related_keys)

        for source_key, group in candidate_frame.groupby(
            "source_series_key",
            sort=False,
            dropna=False,
        ):
            reasons: list[str] = []
            if len(str(source_key)) > 80:
                reasons.append("SERIES_ID_TOO_LONG")
            if str(source_key) in conflicting_source_keys:
                reasons.append("URL_TO_SERIES_KEY_CONFLICT")
            for column in (
                "league",
                "year",
                "split",
                "playoffs",
                "team_pair",
                "best_of",
            ):
                if len(group[column].drop_duplicates()) != 1:
                    reasons.append(f"SERIES_{column.upper()}_CONFLICT")

            game_numbers = [int(value) for value in group["game_number"]]
            if len(game_numbers) != len(set(game_numbers)):
                reasons.append("DUPLICATE_SERIES_GAME_NUMBER")
            if any(value < 1 for value in game_numbers):
                reasons.append("INVALID_SERIES_GAME_NUMBER")
            if game_numbers and sorted(game_numbers) != list(
                range(1, max(game_numbers) + 1)
            ):
                reasons.append("NON_CONTIGUOUS_SERIES_GAME_NUMBER")
            best_of_values = group["best_of"].drop_duplicates().tolist()
            if best_of_values and any(
                value > int(best_of_values[0]) for value in game_numbers
            ):
                reasons.append("GAME_NUMBER_EXCEEDS_EXPLICIT_BEST_OF")

            ordered = group.sort_values("game_number", kind="stable")
            dates = ordered["date"].tolist()
            if any(later < earlier for earlier, later in zip(dates, dates[1:])):
                reasons.append("SERIES_DATE_ORDER_CONFLICT")

            non_missing_url_keys = {
                str(value)
                for value in group["url_series_key"].tolist()
                if not _is_missing(value)
            }
            if len(non_missing_url_keys) > 1:
                reasons.append("URL_TO_SERIES_KEY_CONFLICT")

            status = SERIES_READY if not reasons else SERIES_BLOCKED
            reason = "SOURCE_SERIES_AND_BEST_OF_EXPLICIT"
            if reasons:
                reason = ",".join(sorted(set(reasons)))
            diagnostics.append(
                {
                    "source_key": str(source_key),
                    "status": status,
                    "reason": reason,
                    "detail": f"games={len(group)}",
                }
            )

            for gameid in group["gameid"].tolist():
                assignments.append(
                    {
                        "gameid": str(gameid),
                        "series_id": (
                            str(source_key) if status == SERIES_READY else pd.NA
                        ),
                        "series_status": status,
                        "series_reason": reason,
                    }
                )

            if status == SERIES_READY:
                first = group.iloc[0]
                series_records.append(
                    {
                        "series_id": str(source_key),
                        "source_series_key": str(source_key),
                        "league": first["league"],
                        "year": first["year"],
                        "split": first["split"],
                        "playoffs": first["playoffs"],
                        "best_of": int(first["best_of"]),
                    }
                )

    for row in metadata_rejected.itertuples(index=False):
        diagnostics.append(
            {
                "source_key": str(row.source_key),
                "status": SERIES_BLOCKED,
                "reason": str(row.reason),
                "detail": str(row.detail),
            }
        )
    if games.empty:
        diagnostics.append(
            {
                "source_key": "oracle_source",
                "status": SERIES_BLOCKED,
                "reason": "NO_VALID_GAME_METADATA",
                "detail": "No valid source game remains for series analysis.",
            }
        )

    assignment_frame = _records_frame(assignments, _SERIES_ASSIGNMENT_COLUMNS)
    if not assignment_frame.empty:
        assignment_frame = assignment_frame.drop_duplicates(
            subset=["gameid"],
            keep="last",
        ).reset_index(drop=True)
    diagnostic_frame = _records_frame(
        diagnostics,
        _SERIES_DIAGNOSTIC_COLUMNS,
    )
    series_frame = _records_frame(series_records, _SERIES_RECORD_COLUMNS)
    overall_status = SERIES_BLOCKED
    if (
        not games.empty
        and not assignment_frame.empty
        and not series_frame.empty
        and not bool(diagnostic_frame["status"].eq(SERIES_BLOCKED).any())
    ):
        overall_status = SERIES_READY

    return OracleSeriesAnalysis(
        status=overall_status,
        series_records=series_frame,
        diagnostics=diagnostic_frame,
        game_assignments=assignment_frame,
    )


def _unique_source_names(
    dataframe: pd.DataFrame,
    *,
    id_column: str,
    name_column: str,
    entity: str,
    maximum: int,
) -> tuple[dict[str, str], list[dict[str, str]]]:
    names: dict[str, str] = {}
    issues: list[dict[str, str]] = []
    eligible = dataframe.loc[~dataframe[id_column].map(_is_missing)]
    for source_id, group in eligible.groupby(id_column, sort=False, dropna=False):
        cleaned_names = {
            name
            for value in group[name_column].tolist()
            if (name := _text_or_none(value)) is not None
        }
        canonical_names = {canonical_key(name) for name in cleaned_names}
        if not cleaned_names:
            issues.append(
                _issue(entity, source_id, "MISSING_SOURCE_NAME", name_column)
            )
            continue
        if len(canonical_names) != 1 or len(cleaned_names) != 1:
            issues.append(
                _issue(
                    entity,
                    source_id,
                    "SOURCE_NAME_CONFLICT",
                    repr(sorted(cleaned_names)),
                )
            )
            continue
        name = next(iter(cleaned_names))
        if len(name) > maximum:
            issues.append(
                _issue(entity, source_id, "SOURCE_NAME_TOO_LONG", str(len(name)))
            )
            continue
        names[str(source_id)] = name
    return names, issues


def _snapshot_index(
    dataframe: pd.DataFrame,
    key_column: str,
) -> dict[str, dict[str, object]]:
    if dataframe.empty:
        return {}
    if key_column not in dataframe.columns:
        raise ValueError(f"Target snapshot is missing column: {key_column}")
    if bool(dataframe[key_column].map(_is_missing).any()):
        raise ValueError(f"Target snapshot has missing {key_column} values.")
    if bool(dataframe.duplicated(subset=[key_column]).any()):
        raise ValueError(f"Target snapshot has duplicate {key_column} values.")
    return {
        str(row[key_column]): row.to_dict()
        for _, row in dataframe.iterrows()
    }


def _snapshot_source_index(
    dataframe: pd.DataFrame,
    *,
    target_id_column: str,
    source_id_column: str,
) -> dict[str, str]:
    if dataframe.empty:
        return {}
    required = {target_id_column, source_id_column}
    if not required <= set(dataframe.columns):
        missing = ", ".join(sorted(required - set(dataframe.columns)))
        raise ValueError(f"Target snapshot is missing source-ID columns: {missing}")

    index: dict[str, str] = {}
    for row in dataframe.itertuples(index=False):
        source_id = getattr(row, source_id_column)
        if _is_missing(source_id):
            continue
        source_key = str(source_id)
        target_id = str(getattr(row, target_id_column))
        previous = index.get(source_key)
        if previous is not None and previous != target_id:
            raise ValueError(
                f"Target snapshot maps {source_id_column}={source_key} "
                "to multiple target IDs."
            )
        index[source_key] = target_id
    return index


def _build_team_records(
    identities: OracleIdentityResult,
    snapshot: OracleTargetSnapshot,
) -> tuple[pd.DataFrame, dict[str, str], list[dict[str, str]]]:
    source = identities.team_participations
    names, name_issues = _unique_source_names(
        source,
        id_column="resolved_oracle_team_id",
        name_column="source_teamname",
        entity="team",
        maximum=150,
    )
    issues: list[dict[str, str]] = []
    name_issues_by_id: dict[str, list[dict[str, str]]] = {}
    for issue in name_issues:
        name_issues_by_id.setdefault(issue["source_key"], []).append(issue)
    existing = _snapshot_index(snapshot.teams, "team_id")
    existing_by_source = _snapshot_source_index(
        snapshot.teams,
        target_id_column="team_id",
        source_id_column="oracle_team_id",
    )
    source_to_target: dict[str, str] = {}
    records: list[dict[str, object]] = []

    for source_id, group in source.loc[
        ~source["resolved_oracle_team_id"].map(_is_missing)
    ].groupby("resolved_oracle_team_id", sort=False, dropna=False):
        oracle_id = str(source_id)
        statuses = set(group["team_target_status"].astype(str).tolist())
        target_ids = {
            str(value)
            for value in group["target_team_id"].tolist()
            if not _is_missing(value)
        }
        if len(statuses) != 1:
            issues.append(
                _issue("team", oracle_id, "TARGET_STATUS_CONFLICT", repr(statuses))
            )
            continue
        status = next(iter(statuses))
        if status == TARGET_CONFLICT:
            issues.append(
                _issue("team", oracle_id, "TARGET_ORACLE_ID_CONFLICT", "")
            )
            continue
        if status == TARGET_EXISTING:
            if len(target_ids) != 1:
                issues.append(
                    _issue("team", oracle_id, "TARGET_ID_MISSING", repr(target_ids))
                )
                continue
            target_id = next(iter(target_ids))
            target = existing.get(target_id)
            if target is None:
                issues.append(
                    _issue("team", oracle_id, "TARGET_SNAPSHOT_MISSING", target_id)
                )
                continue
            if existing_by_source.get(oracle_id) != target_id:
                issues.append(
                    _issue(
                        "team",
                        oracle_id,
                        "TARGET_ORACLE_ID_MISMATCH",
                        target_id,
                    )
                )
                continue
            record = {
                column: target.get(column) for column in TEAM_COLUMNS
            }
        elif status == TARGET_NEW_REQUIRED:
            known_target_id = existing_by_source.get(oracle_id)
            if known_target_id is not None:
                target_id = known_target_id
                record = {
                    column: existing[target_id].get(column)
                    for column in TEAM_COLUMNS
                }
            else:
                target_id = oracle_id
                occupied = existing.get(target_id)
                if occupied is None:
                    if oracle_id not in names:
                        issues.extend(name_issues_by_id.get(oracle_id, ()))
                        continue
                    record = {
                        "team_id": target_id,
                        "oracle_team_id": oracle_id,
                        "canonical_name": names[oracle_id],
                        "display_name": names[oracle_id],
                        "logo_file": None,
                    }
                elif str(occupied.get("oracle_team_id")) != oracle_id:
                    issues.append(
                        _issue(
                            "team",
                            oracle_id,
                            "TARGET_PRIMARY_KEY_COLLISION",
                            target_id,
                        )
                    )
                    continue
                else:
                    record = {
                        column: occupied.get(column) for column in TEAM_COLUMNS
                    }
        else:
            issues.append(
                _issue("team", oracle_id, "TARGET_STATUS_UNSUPPORTED", status)
            )
            continue

        source_to_target[oracle_id] = target_id
        records.append(record)

    return _records_frame(records, TEAM_COLUMNS), source_to_target, issues


