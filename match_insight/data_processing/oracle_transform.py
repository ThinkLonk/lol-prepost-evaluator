def _stage_name(split: object, playoffs: int) -> str | None:
    split_name = _text_or_none(split)
    if split_name is None:
        return None
    return f"{split_name} Playoffs" if playoffs == 1 else split_name


def _build_context_records(
    games: pd.DataFrame,
) -> tuple[
    pd.DataFrame,
    pd.DataFrame,
    pd.DataFrame,
    dict[tuple[str, int], str],
    dict[tuple[str, int, str | None, int], str],
    list[dict[str, str]],
]:
    patches: list[dict[str, object]] = []
    tournaments: list[dict[str, object]] = []
    stages: list[dict[str, object]] = []
    issues: list[dict[str, str]] = []
    tournament_ids: dict[tuple[str, int], str] = {}
    stage_ids: dict[tuple[str, int, str | None, int], str] = {}

    for patch in games["patch"].drop_duplicates().tolist():
        patch_text = str(patch)
        patches.append({"patch_id": patch_text, "patch_name": patch_text})

    contexts = games[["league", "year", "split", "playoffs"]].drop_duplicates()
    for row in contexts.itertuples(index=False):
        league = _text_or_none(row.league)
        season = int(row.year)
        playoffs = int(row.playoffs)
        split = _text_or_none(row.split)
        source_key = f"{league}|{season}|{split}|{playoffs}"
        if league is None or len(league) > 150:
            issues.append(
                _issue("tournament", source_key, "INVALID_LEAGUE", str(row.league))
            )
            continue
        if playoffs not in {0, 1}:
            issues.append(
                _issue("tournament_stage", source_key, "INVALID_PLAYOFFS", str(playoffs))
            )
            continue
        stage_name = _stage_name(split, playoffs)
        if stage_name is None or len(stage_name) > 100:
            issues.append(
                _issue(
                    "tournament_stage",
                    source_key,
                    "INSUFFICIENT_STAGE_CONTEXT",
                    "split is missing or the stage name exceeds 100 characters",
                )
            )
            continue

        tournament_key = (league, season)
        tournament_id = tournament_ids.get(tournament_key)
        if tournament_id is None:
            tournament_id = _stable_id(
                "oracle:tournament:",
                canonical_key(league),
                season,
            )
            tournament_ids[tournament_key] = tournament_id
            tournaments.append(
                {
                    "tournament_id": tournament_id,
                    "name": league,
                    "region": None,
                    "season": season,
                }
            )

        stage_key = (league, season, split, playoffs)
        if stage_key in stage_ids:
            continue
        stage_id = _stable_id(
            "oracle:stage:",
            tournament_id,
            split,
            playoffs,
        )
        stage_ids[stage_key] = stage_id
        stages.append(
            {
                "stage_id": stage_id,
                "tournament_id": tournament_id,
                "name": stage_name,
            }
        )

    return (
        _records_frame(patches, GAME_PATCH_COLUMNS),
        _records_frame(tournaments, TOURNAMENT_COLUMNS),
        _records_frame(stages, TOURNAMENT_STAGE_COLUMNS),
        tournament_ids,
        stage_ids,
        issues,
    )


