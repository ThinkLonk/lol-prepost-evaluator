    for row in unresolved_players.itertuples(index=True):
        issues.append(
            _issue(
                "player_row",
                f"{row.gameid}|{row.side}|{row.position}|{row.Index}",
                str(row.player_resolution_reason),
                repr(row.player_resolution_candidates),
            )
        )
    return issues


